import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('standalone HTML runs offline with no external assets, saves players and generates teams', async ({ page, context }) => {
  // This cloud browser blocks all file:// navigation by administrator policy.
  // Fulfill only the document from disk; all actual network access is offline.
  const url = 'http://127.0.0.1:5173/Sideline.html';
  const html = await readFile(new URL('../standalone/Sideline.html', import.meta.url), 'utf8');
  const errors = [];
  const network = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => { if (/^https?:/.test(request.url()) && request.url() !== url) network.push(request.url()); });
  await page.route(url, (route) => route.fulfill({ body: html, contentType: 'text/html' }));
  await context.setOffline(true);
  await page.goto(url);
  await expect(page.getByRole('heading', { name: 'Less planning. More playing.' })).toBeVisible();
  await page.getByRole('button', { name: /Player roster/ }).click();
  await page.getByRole('button', { name: 'Add player', exact: true }).click();
  await page.getByLabel('Player name').fill('Offline Player');
  await page.getByLabel('Skill rating', { exact: true }).fill('90');
  await page.getByRole('button', { name: 'Add player', exact: true }).last().click();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Offline Player, skill 90' })).toBeVisible();
  await page.getByRole('button', { name: 'Generate teams' }).click();
  await expect(page.getByRole('heading', { name: 'Team A', exact: true })).toBeVisible();
  await expect(page.locator('.team-player-list li')).toHaveCount(13);
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined }));
  await page.getByRole('button', { name: 'Copy teams for WhatsApp' }).click();
  await expect(page.getByRole('textbox', { name: 'Team lists to copy' })).toContainText('Offline Player (90)');
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: 'Create tournament', exact: true }).click();
  await page.getByLabel('Tournament name', { exact: true }).fill('Offline Cup');
  await page.getByRole('checkbox', { name: 'Schedule kickoff times' }).uncheck();
  await page.getByRole('button', { name: 'Create tournament', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Offline Cup', exact: true })).toBeVisible();
  const fixture = page.locator('.fixture-row').first();
  await fixture.getByRole('spinbutton').first().fill('2');
  await fixture.getByRole('spinbutton').last().fill('1');
  await fixture.getByRole('button', { name: /Save result for/ }).click();
  await expect(page.locator('.champion-banner')).toContainText('YOUR CHAMPIONS');
  const cup = await page.evaluate(() => { const data = JSON.parse(localStorage.getItem('sideline.tournaments.v1')); return data.tournaments.find(item => item.id === data.activeId); });
  const match = cup.fixtures[0];
  const home = cup.teams.find(team => team.id === match.homeId);
  const away = cup.teams.find(team => team.id === match.awayId);
  await page.getByRole('button', { name: `Goalscorers for ${home.name} vs ${away.name}`, exact: true }).click();
  await page.getByRole('button', { name: `Add scorer for ${home.name}`, exact: true }).click();
  await page.getByLabel(`Goalscorer 1 for ${home.name}`, { exact: true }).selectOption(home.players[0].id);
  await page.getByLabel(`Goals by scorer 1 for ${home.name}`, { exact: true }).fill('2');
  await page.getByRole('button', { name: `Add scorer for ${away.name}`, exact: true }).click();
  await page.getByLabel(`Goalscorer 1 for ${away.name}`, { exact: true }).selectOption(away.players[0].id);
  await page.getByRole('button', { name: 'Save goalscorers', exact: true }).click();
  await expect(page.locator('.golden-boot-banner')).toContainText(home.players[0].name);
  await page.reload();
  await page.getByRole('button', { name: 'Tournaments', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Offline Cup', exact: true })).toBeVisible();
  await expect(page.locator('.fixture-row').first().getByRole('spinbutton').first()).toHaveValue('2');
  await expect(page.locator('.fixture-row').first().getByRole('spinbutton').last()).toHaveValue('1');
  await expect(page.locator('.champion-banner')).toContainText('YOUR CHAMPIONS');
  await expect(page.locator('.golden-boot-banner')).toContainText(home.players[0].name);
  expect(errors).toEqual([]);
  expect(network).toEqual([]);
});
